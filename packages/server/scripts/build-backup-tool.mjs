// Builds the standalone backup tool.
//
// PostgreSQL invokes the archiver for every completed WAL segment, so the tool
// must run as a single self-contained script under plain node with no
// transpiler in the path. Everything the backup subsystem needs is bundled
// here; nothing from the application is required to run it.
//
//   node scripts/build-backup-tool.mjs
import { build } from "esbuild";
import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "..", "dist", "backup");

await mkdir(out, { recursive: true });

await build({
  entryPoints: [resolve(here, "nexora-backup.ts")],
  outfile: resolve(out, "nexora-backup.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  // Only Node built-ins and the backup subsystem: the archiver must not drag in
  // the database pool, the config loader or anything else the app needs.
  external: ["pg"],
  banner: {
    js: "// Nexora backup tool - generated by scripts/build-backup-tool.mjs. Do not edit."
  },
  logLevel: "warning"
});

// The shipper is the long-running process that drains the staging directory,
// replicates objects, takes scheduled base backups and applies retention.
await build({
  entryPoints: [resolve(here, "nexora-shipper.ts")],
  outfile: resolve(out, "nexora-shipper.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["pg"],
  banner: {
    js: "// Nexora backup shipper - generated by scripts/build-backup-tool.mjs. Do not edit."
  },
  logLevel: "warning"
});

console.log(`backup tool and shipper written to ${out}`);
